"""Library-driven size oracle for the V3 peak-RAM estimator (backend-neutral).

V3 object sizes come from the Lattigo library itself (BinarySize of empty
objects, generated by lattigo_backend/v3_size_oracle.go into
RL/v3_size_oracle_table.csv), NOT from analytic formulas. The formulas in
memory_layout.py are kept only as unit-test cross-checks (0.1% tolerance).

Backend-neutral interface: object_bytes(kind, params). A backend plugs in by
contributing a generated oracle table keyed by its backend name; backends
without a table are unsupported (LookupError) rather than approximated.
"""
from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path

ORACLE_TABLE_PATH = Path(__file__).resolve().parent.parent / "v3_size_oracle_table.csv"

# Kinds emitted by the Lattigo oracle.
KINDS = (
    "secret_key",
    "public_key",
    "relinearization_key",
    "galois_key",
    "ciphertext_deg1",
    "plaintext_max_level",
)


@dataclass(frozen=True)
class OracleParams:
    """Backend-neutral parameter triple for oracle lookup."""

    log_n: int
    n_q: int
    n_p: int
    backend: str = "lattigo"

    @classmethod
    def from_fhe_params(cls, params, backend: str = "lattigo"):
        """Build from pytrs.peak_ram.FHEParams using that backend's Q/P split."""
        return cls(
            log_n=params.poly_modulus_degree.bit_length() - 1,
            n_q=params.nQ(backend),
            n_p=params.nP(backend),
            backend=backend.lower(),
        )


_TABLE_CACHE: dict = {}


def _load_table() -> dict:
    if _TABLE_CACHE:
        return _TABLE_CACHE
    with ORACLE_TABLE_PATH.open() as handle:
        for row in csv.DictReader(handle):
            _TABLE_CACHE[
                (
                    "lattigo",
                    row["kind"],
                    int(row["logN"]),
                    int(row["nQ"]),
                    int(row["nP"]),
                )
            ] = int(row["bytes"])
    return _TABLE_CACHE


def object_bytes(kind: str, params: OracleParams) -> int:
    """Bytes for ONE object of `kind` at `params`, from the library oracle."""
    if kind not in KINDS:
        raise ValueError(f"unknown oracle kind: {kind}")
    table = _load_table()
    key = (params.backend.lower(), kind, params.log_n, params.n_q, params.n_p)
    try:
        return table[key]
    except KeyError:
        raise LookupError(
            f"no size oracle entry for backend={key[0]} kind={key[1]} "
            f"logN={key[2]} nQ={key[3]} nP={key[4]}; regenerate "
            "RL/v3_size_oracle_table.csv via lattigo_backend/v3_size_oracle.go"
        ) from None
